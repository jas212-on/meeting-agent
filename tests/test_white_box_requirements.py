    def test_wb_03_auth_middleware_missing_or_invalid_token(self, driver, frontend_url, backend_url):
        """WB-03: authMiddleware.authenticateToken().
        
        Technique: Decision Coverage
        Paths/Conditions: Missing / invalid Bearer token -> HTTP 401 rejection branch
        Result: Pass
        """
        # Visually verify unauthenticated browser access triggers Auth screen
        driver.get(frontend_url)
        driver.execute_script("localStorage.removeItem('auth_token'); localStorage.removeItem('user_profile');")
        driver.refresh()
        time.sleep(0.8)

        wait = WebDriverWait(driver, 10)
        auth_mounted = wait.until(
            lambda d: len(d.find_elements(By.CLASS_NAME, "auth-page-container")) > 0
            or len(d.find_elements(By.ID, "auth-email")) > 0
        )
        assert auth_mounted, "Unauthenticated user must be routed to Auth screen"
        time.sleep(0.8)

        # Backend API validation of rejection branches
        res_missing = requests.get(f"{backend_url}/api/groups", timeout=5)
        assert res_missing.status_code in [401, 403], "Missing token must be rejected"

        res_invalid = requests.get(
            f"{backend_url}/api/groups",
            headers={"Authorization": "Bearer malformed_token_invalid_signature"},
            timeout=5,
        )
        assert res_invalid.status_code in [401, 403], "Invalid token must be rejected"
        print("\n[WB-03] Validated missing/invalid token rejection branches visually and via API")

    def test_wb_04_auth_login_mismatched_password(self, driver, frontend_url, backend_url):
        """WB-04: authController.loginUser().
        
        Technique: Condition Coverage
        Paths/Conditions: Valid email with mismatched password (bcrypt.compare returns false) -> HTTP 401
        Result: Pass
        """
        driver.get(frontend_url)
        driver.execute_script("localStorage.removeItem('auth_token'); localStorage.removeItem('user_profile');")
        driver.refresh()

        wait = WebDriverWait(driver, 10)
        email_input = wait.until(EC.visibility_of_element_located((By.ID, "auth-email")))
        email_input.clear()
        email_input.send_keys("jason@gmail.com")
        time.sleep(0.4)

        pwd_input = driver.find_element(By.ID, "auth-password")
        pwd_input.clear()
        pwd_input.send_keys("wrong_mismatched_pass_999")
        time.sleep(0.4)

        submit_btn = driver.find_element(By.CLASS_NAME, "auth-primary-submit-btn")
        submit_btn.click()
        time.sleep(1.0)

        # Visually assert error rejection banner is displayed
        error_banner = wait.until(EC.visibility_of_element_located((By.CLASS_NAME, "form-error")))
        assert error_banner.is_displayed(), "Rejection banner must appear for mismatched password"
        time.sleep(0.8)

        # Backend assertion
        res = requests.post(
            f"{backend_url}/api/auth/login",
            json={"email": "jason@gmail.com", "password": "wrong_mismatched_pass_999"},
            headers={"Content-Type": "application/json", "x-test-suite": "true"},
            timeout=5,
        )
        assert res.status_code == 401
        print("\n[WB-04] Validated login mismatched password branch (bcrypt.compare == false -> 401)")

    def test_wb_05_group_creation_duplicate_name_conflict(self, dashboard_page, backend_url):
        """WB-05: groupController.createGroup().
        
        Technique: Decision Coverage
        Paths/Conditions: Duplicate group name check (Group.findOne returns existing record) -> HTTP 409 Conflict
        Result: Pass
        """
        driver = dashboard_page
        wait = WebDriverWait(driver, 10)
        duplicate_name = f"Duplicate Workspace {int(time.time() * 1000)}"

        # Get the token of the currently authenticated browser session
        current_token = driver.execute_script("return localStorage.getItem('auth_token');")
        assert current_token, "Expected active auth token in browser"

        # Pre-create the group via API under the active user
        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {current_token}",
            "x-test-suite": "true",
        }
        res_initial = requests.post(
            f"{backend_url}/api/groups",
            json={"name": duplicate_name, "description": "First instance"},
            headers=headers,
            timeout=10,
        )
        assert res_initial.status_code == 201

        # Now attempt duplicate creation in the browser UI
        create_btn = wait.until(EC.element_to_be_clickable((By.CLASS_NAME, "btn-create-group")))
        driver.execute_script("arguments[0].scrollIntoView({behavior: 'smooth', block: 'center'});", create_btn)
        time.sleep(0.4)
        create_btn.click()

        name_input = wait.until(EC.visibility_of_element_located((By.ID, "group-name-input")))
        name_input.clear()
        name_input.send_keys(duplicate_name)
        time.sleep(0.4)

        submit_btn = driver.find_element(By.CLASS_NAME, "btn-modal-submit")
        driver.execute_script("arguments[0].click();", submit_btn)
        time.sleep(1.0)

        # Assert duplicate error banner appears in browser
        error_alert = wait.until(EC.visibility_of_element_located((By.CLASS_NAME, "form-alert-error")))
        assert error_alert.is_displayed(), "Expected duplicate name error alert in UI"
        time.sleep(0.8)

        # Close modal
        close_btn = driver.find_element(By.CLASS_NAME, "modal-close-btn")
        close_btn.click()
        time.sleep(0.3)

        # API assertion: second creation returns HTTP 409 Conflict
        res_duplicate = requests.post(
            f"{backend_url}/api/groups",
            json={"name": duplicate_name, "description": "Second instance"},
            headers=headers,
            timeout=10,
        )
        assert res_duplicate.status_code == 409, f"Expected 409 Conflict, got {res_duplicate.status_code}"
        print("\n[WB-05] Validated duplicate group check -> HTTP 409 Conflict rejection branch in browser & API")

